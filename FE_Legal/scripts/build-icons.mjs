// Copies the handful of Tabler icons the app uses into src/icons.js, so the bundle
// carries ~40 icons instead of the whole set. Add a name to NAMES and run `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const NAMES = [
  'inbox', 'archive', 'gavel', 'file-certificate', 'hammer', 'circle-check', 'chevron-left', 'chevron-right',
  'chevron-down', 'chevron-up', 'arrow-right', 'arrow-left', 'arrow-up', 'arrow-down', 'plus', 'minus', 'search',
  'user', 'users', 'wallet', 'cash', 'building-bank', 'settings', 'logout', 'photo', 'x', 'check', 'edit', 'trash',
  'clock', 'refresh', 'alert-triangle', 'alert-circle', 'info-circle', 'scale', 'send', 'ban', 'receipt', 'notes',
  'history', 'phone', 'briefcase', 'coin', 'list-check', 'calendar', 'route', 'square', 'square-check',
  'square-minus', 'circle', 'circle-dot', 'caret-down', 'menu-2', 'selector', 'paperclip', 'chevrons-left',
  'chevrons-right', 'arrow-back-up', 'player-play', 'file-text', 'transfer', 'cash-banknote', 'report-money',
  'user-check', 'eye', 'star', 'star-filled',
]

const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/tabler/icons.json'), 'utf8'))
const out = {}
const missing = []
for (const name of NAMES) {
  const icon = set.icons[name] || set.icons[set.aliases?.[name]?.parent]
  if (icon)
    out[name] = icon.body
  else
    missing.push(name)
}
if (missing.length)
  console.warn('Missing icons:', missing.join(', '))
writeFileSync(new URL('../src/icons.js', import.meta.url),
  `// Generated by scripts/build-icons.mjs from @iconify-json/tabler (MIT). Do not edit by hand.\nexport const ICONS = ${JSON.stringify(out, null, 2)}\n`)
console.log(`Wrote ${Object.keys(out).length} icons`)
