        [IdentityDocumentNumber] = @IdentityDocumentNumber,
        [Address] = @Address,
        [PhoneNumber] = @PhoneNumber,
        [ReceiverSignature] = @ReceiverSignature,
        [DelivererSignature] = @DelivererSignature,
        [FirstWitnessName] = @FirstWitnessName,
        [FirstWitnessSignature] = @FirstWitnessSignature,
        [SecondWitnessName] = @SecondWitnessName,
        [SecondWitnessSignature] = @SecondWitnessSignature,
        [FirstPartySignature] = @FirstPartySignature,
        [SecondPartySignature] = @SecondPartySignature,
        [CashierSignature] = @CashierSignature,
        [SalesRepresentativeSignature] = @SalesRepresentativeSignature,
        [SalesRepresentativeName] = @SalesRepresentativeName,
        [CashierName] = @CashierName,
        [DelegateID] = @DelegateID,
        [UpdatedByUserID] = @UpdatedByUserID,
        [UpdatedDate] = GETDATE(),
        [IsActive] = @IsActive
    WHERE
        [TrustReceiptID] = @TrustReceiptID;
END
