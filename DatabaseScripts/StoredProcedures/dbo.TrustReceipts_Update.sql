    @SalesRepresentativeName NVARCHAR(255) = NULL,
    @CashierName NVARCHAR(255) = NULL,
    @DelegateID INT = NULL,
    @UpdatedByUserID INT = NULL,
    @IsActive BIT = 1
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE [dbo].[TrustReceipts]
    SET
        [ContractNumber] = @ContractNumber,
        [ContractDate] = @ContractDate,
        [ContractType] = @ContractType,
        [ContractNotes] = @ContractNotes,
        [ContractStatus] = @ContractStatus,
        [FirstPartyName] = @FirstPartyName,
        [CompanyType] = @CompanyType,
        [CompanyRepresentativeName] = @CompanyRepresentativeName,
        [CompanyRepresentativeRole] = @CompanyRepresentativeRole,
        [BuyerID] = @BuyerID,
        [BuyerName] = @BuyerName,
